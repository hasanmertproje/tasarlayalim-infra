const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ts=require('typescript');
const source=fs.readFileSync(require('node:path').join(__dirname,'../src/publisherDocument.ts'),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
const loaded={exports:{}};vm.runInNewContext(output,{module:loaded,exports:loaded.exports,String});
const {renderSiteHtml,technologyFiles,escapeHtml}=loaded.exports;
assert.equal(escapeHtml('<img src=x onerror="alert(1)">'),'&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
const html=renderSiteHtml([{id:'1',type:'hero',label:'hero',value:'X & <img src=x onerror=alert(1)> <script>alert(9)</script>'}], 'My <title>');
assert(html.includes('&lt;img src=x onerror=alert(1)&gt;'));
assert(!html.includes('<img src=x'));
assert(!html.includes('<script>'));
assert(html.includes('script-src'));
assert(html.includes('My &lt;title&gt;'));
assert(technologyFiles('html').includes('index.html'));
assert(technologyFiles('laravel').includes('routes/web.php'));
assert(technologyFiles('react').includes('src/App.tsx'));
const domainSource=fs.readFileSync(require('node:path').join(__dirname,'../src/domain.ts'),'utf8');
const domainOutput=ts.transpileModule(domainSource,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
const scoped={exports:{}};vm.runInNewContext(domainOutput,{module:scoped,exports:scoped.exports});
const {INITIAL,projectBlocks}=scoped.exports;
assert.equal(projectBlocks(INITIAL,'pr-1')[0].value,'Bir fikri birlikte hayata geçirelim.');
assert.equal(projectBlocks(INITIAL,'pr-2')[0].value,'EntegrePilot ile yeni fikirler');
const edited={...INITIAL,studioDocuments:{'pr-2':[{id:'custom',type:'hero',label:'Test',value:'İzole proje metni'}]}};
assert.equal(projectBlocks(edited,'pr-2')[0].value,'İzole proje metni');
assert.equal(projectBlocks(edited,'pr-1')[0].value,'Bir fikri birlikte hayata geçirelim.');
console.log('Publisher document unit contracts: PASS (safe content, CSP, manifests and project-scoped documents)');
