import assert from 'node:assert/strict';
import test from 'node:test';
import type { Mission, MissionStep } from '../src/domain.js';
import { MissionExecutor } from '../src/mission-executor.js';
import type { ProviderDescriptor } from '../src/provider-router.js';
import { ProviderRouter } from '../src/provider-router.js';
import { ProjectRegistry } from '../src/project-registry.js';
import { TaskEngine } from '../src/task-engine.js';

const providers: ProviderDescriptor[] = [{
  id: 'private-test',
  displayName: 'Private Test',
  enabled: true,
  costClass: 'free',
  strength: 100,
  latency: 10,
  allowedDataClasses: ['private_code'],
}];

function setup(previewRequired = false) {
  const projects = new ProjectRegistry();
  const project = projects.create({
    slug: 'orchestrator-v2',
    name: 'Orchestrator V2',
    repository: 'example/orchestrator-v2',
    isExisting: true,
  });
  const tasks = new TaskEngine(projects, new ProviderRouter(providers));
  const mission = tasks.createMission({
    projectId: project.id,
    objective: 'Build frontend and backend feature',
    riskLevel: 'WRITE',
    dataClass: 'private_code',
    autonomous: { previewRequired },
  });
  return { projects, project, tasks, mission };
}

function fakeGithub() {
  return {
    readiness: () => ({ configured: true }),
    listFiles: async () => ['src/App.tsx', 'src/api.ts'],
    readFiles: async (_repository: string, _branch: string, paths: string[]) => paths.map((path) => ({ path, content: `// ${path}` })),
    createPullRequestWithChanges: async (input: { branch: string }) => ({
      branch: input.branch,
      commitSha: 'abc123456789',
      number: 71,
      url: 'https://github.com/example/orchestrator-v2/pull/71',
    }),
    waitForChecks: async () => 'success' as const,
  };
}

function plannerFor(steps: MissionStep[], conflicting = false) {
  return {
    readiness: () => ({ configured: true, providers: [], legacy: false }),
    chooseFiles: async () => ['src/App.tsx', 'src/api.ts'],
    analyze: async () => 'unused',
    planChanges: async () => ({ summary: 'unused', commitMessage: 'unused', files: [] }),
    decomposeMission: async () => ({ summary: 'Two specialist work items.', steps }),
    planStepChanges: async (_project: unknown, _mission: Mission, _files: unknown[], step: MissionStep) => ({
      summary: `${step.specialist} completed ${step.id}`,
      commitMessage: `${step.specialist}: ${step.id}`,
      files: [{
        path: conflicting ? 'src/shared.ts' : step.targetPaths[0]!,
        content: conflicting ? `// generated by ${step.id}` : `// completed by ${step.specialist}`,
      }],
    }),
  };
}

const independentSteps: MissionStep[] = [
  {
    id: 'frontend-ui',
    title: 'Build UI',
    objective: 'Implement the frontend surface.',
    specialist: 'frontend',
    status: 'queued',
    dependsOn: [],
    targetPaths: ['src/App.tsx'],
    progress: 0,
  },
  {
    id: 'backend-api',
    title: 'Build API',
    objective: 'Implement the backend integration.',
    specialist: 'backend',
    status: 'queued',
    dependsOn: [],
    targetPaths: ['src/api.ts'],
    progress: 0,
  },
];

test('Mission Orchestrator V2 executes specialist work items and persists artifacts', async () => {
  const { projects, tasks, mission } = setup(false);
  const executor = new MissionExecutor(tasks, projects, plannerFor(independentSteps) as any, fakeGithub() as any, undefined, { planningTimeoutMs: 10_000 });

  const completed = await executor.execute(mission.id);

  assert.equal(completed.status, 'completed');
  assert.equal(completed.execution?.workPlan?.length, 2);
  assert.deepEqual(completed.execution?.workPlan?.map((step) => step.status), ['completed', 'completed']);
  assert.ok((completed.execution?.artifacts ?? []).some((artifact) => artifact.type === 'file-change' && artifact.path === 'src/App.tsx'));
  assert.ok((completed.execution?.artifacts ?? []).some((artifact) => artifact.type === 'file-change' && artifact.path === 'src/api.ts'));
  assert.ok((completed.execution?.artifacts ?? []).some((artifact) => artifact.type === 'pull-request'));
  assert.ok((completed.execution?.artifacts ?? []).some((artifact) => artifact.type === 'ci'));
  assert.ok((completed.execution?.agentRuns ?? []).some((run) => run.label === 'Frontend Engineer Worker'));
  assert.ok((completed.execution?.agentRuns ?? []).some((run) => run.label === 'Backend Engineer Worker'));
  assert.ok((completed.execution?.agentRuns ?? []).some((run) => run.label === 'Repository Publisher'));
});

test('dependent specialist work receives an explicit artifact handoff', async () => {
  const { projects, tasks, mission } = setup(false);
  const dependentSteps: MissionStep[] = [
    independentSteps[0]!,
    { ...independentSteps[1]!, dependsOn: ['frontend-ui'] },
  ];
  const executor = new MissionExecutor(tasks, projects, plannerFor(dependentSteps) as any, fakeGithub() as any, undefined, { planningTimeoutMs: 10_000 });

  const completed = await executor.execute(mission.id);
  const handoff = completed.execution?.handoffs?.[0];

  assert.equal(completed.status, 'completed');
  assert.equal(handoff?.fromStepId, 'frontend-ui');
  assert.equal(handoff?.toStepId, 'backend-api');
  assert.ok((handoff?.artifactIds.length ?? 0) >= 1);
});

test('conflicting specialist file outputs fail instead of silently overwriting', async () => {
  const { projects, tasks, mission } = setup(false);
  const conflictingSteps: MissionStep[] = independentSteps.map((step) => ({ ...step, targetPaths: [] }));
  const executor = new MissionExecutor(tasks, projects, plannerFor(conflictingSteps, true) as any, fakeGithub() as any, undefined, { planningTimeoutMs: 10_000 });

  executor.executeSoon(mission.id);
  await new Promise((resolve) => setTimeout(resolve, 50));

  const failed = tasks.getMission(mission.id);
  assert.equal(failed?.status, 'failed');
  assert.match(failed?.execution?.blockedReason ?? '', /conflict on src\/shared\.ts/i);
});
